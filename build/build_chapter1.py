#!/usr/bin/env python3
"""Build the FIN1209 Chapter 1 lecture deck and the instructor answer sheet.

Deterministic and re-runnable: it regenerates both outputs from scratch on
every run, so the committed artefacts are always exactly what this script
produces from build/content_chapter01.py.

Two editions come out of that one content file:

    .venv/bin/python build/build_chapter1.py
    .venv/bin/python build/build_chapter1.py --edition student

Both editions first draw the nine Chapter 1 teaching charts from
build/charts_chapter01.py, so a fresh clone produces the real slide rather
than a placeholder. Those charts are ours; the textbook figures are not, and
they stay out of the repository. See build/README.md.

The teaching edition is the whole deck, checks and reveals and speaker cues
included, and it also writes the instructor's answer sheet. The student
edition is the same deck with every check and every reveal dropped and no
speaker cues, which is the file that can safely be handed out. Neither
edition is a copy of the other: both are rendered from the same content, so
the progress markers are recomputed for whichever slides the edition holds.

See build/README.md for environment setup.

Chapters 2 to 10 are a content file away, not a rewrite: copy the shape of
content_chapter01.py, import it here, and the same helpers in deckkit.py
render it.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import chartkit  # noqa: E402
import deckkit  # noqa: E402
from charts_chapter01 import CHARTS  # noqa: E402
from content_chapter01 import CHAPTER  # noqa: E402

REPO = Path(__file__).resolve().parent.parent
DECK_OUT = REPO / "chapter-01" / "FIN1209-Chapter-01.pptx"
STUDENT_OUT = REPO / "chapter-01" / "FIN1209-Chapter-01-Student-Edition.pptx"
CHECKS_OUT = REPO / "chapter-01" / "in-class-checks.md"

# The committed file each edition writes when --out is not given.
DEFAULT_OUT = {deckkit.TEACHING: DECK_OUT, deckkit.STUDENT: STUDENT_OUT}

# The textbook figures are Wiley's. They are not in this repository, the folder
# is gitignored, and figures are OFF by default on purpose: the plain build has
# to keep reproducing the committed deck exactly, on this machine and on a
# clean clone alike. Pass --with-figures for the instructor's teaching deck.
# Either way the slide count, the progress markers and the checks are identical.
# See chapter-01/README.md for the two commands.
FIGURES_DIR = REPO / "assets" / "figures"

# The charts this course draws for itself are the opposite case to the
# figures: they are ours, so they are generated here from committed code on
# every build and placed in both editions unconditionally. The folder is
# gitignored because it is output, not because anything in it is anyone
# else's. See build/chartkit.py.
CHARTS_DIR = REPO / "build" / "generated" / "charts"


def write_checks(chapter, path: Path, total_checks: int) -> None:
    """The instructor's own answer sheet, generated from the same content the
    deck is built from so the two can never drift apart."""
    out: list[str] = []
    out.append(f"# {chapter.code} {chapter.chapter} - In-class checks")
    out.append("")
    out.append(
        "Every multiple choice item that appears on a check slide, with the "
        "answer and a one-line reason. This file is for the instructor. "
        "It is generated by `build/build_chapter1.py` from "
        "`build/content_chapter01.py`, so it always matches the deck."
    )
    out.append("")
    out.append(
        f"{total_checks} checks, {total_checks * 2} items, two questions each. "
        "In the deck, each check is a question slide followed immediately by "
        "a reveal slide carrying these same answers and reasons."
    )
    out.append("")
    out.append("Answers at a glance:")
    out.append("")
    row = []
    for index, _section, check in deckkit.iter_checks(chapter):
        row.append(f"{index}: {check.questions[0].answer}{check.questions[1].answer}")
    out.append("`" + "   ".join(row) + "`")
    out.append("")

    current_section = None
    for index, section, check in deckkit.iter_checks(chapter):
        if section.number != current_section:
            current_section = section.number
            out.append("")
            out.append(f"## Part {section.number} of 6 - {section.title}")
        out.append("")
        out.append(f"### Check {index} - {check.label}")
        for n, q in enumerate(check.questions, start=1):
            out.append("")
            out.append(f"**Q{n}.** {q.stem}")
            out.append("")
            for j, opt in enumerate(q.options):
                marker = "**" if "ABCD"[j] == q.answer else ""
                out.append(f"- {marker}{'ABCD'[j]}. {opt}{marker}")
            out.append("")
            out.append(f"Answer: **{q.answer}**. {q.reason}")
        out.append("")
    path.write_text("\n".join(out).rstrip() + "\n", encoding="utf-8")


def _relative(path: Path) -> str:
    """Repository relative when it is inside the repository, absolute when the
    instructor's own deck is written outside it."""
    try:
        return str(path.relative_to(REPO))
    except ValueError:
        return str(path)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--display-font",
        default=deckkit.DISPLAY_FONT,
        help=("Typeface for titles and section dividers. Defaults to the FEU "
              "identity face; use a serif such as Palatino if it is not installed."),
    )
    parser.add_argument(
        "--edition",
        choices=deckkit.EDITIONS,
        default=deckkit.TEACHING,
        help=("teaching (default) is the full deck with the checks, the "
              "reveals and the speaker cues. student drops all of those and "
              "is the file that can be handed out."),
    )
    parser.add_argument(
        "--out",
        type=Path,
        default=None,
        help=("Where to write the deck. Defaults to the committed file for "
              "the chosen edition."),
    )
    parser.add_argument(
        "--with-figures",
        action="store_true",
        help=("Place the textbook artwork instead of placeholders. Off by "
              "default: the figures are Wiley's, they are not committed, and "
              "the plain build must keep reproducing the committed deck."),
    )
    parser.add_argument(
        "--figures-dir",
        type=Path,
        default=FIGURES_DIR,
        help="Folder holding the artwork, used only with --with-figures.",
    )
    args = parser.parse_args()
    if args.out is None:
        args.out = DEFAULT_OUT[args.edition]

    figures_dir = args.figures_dir if args.with_figures else None
    if figures_dir is not None and not figures_dir.is_dir():
        parser.error(
            f"--with-figures was given but {figures_dir} does not exist. "
            "The textbook figures are copyrighted and are not in this "
            "repository; see chapter-01/README.md. Drop the flag to build "
            "the placeholder deck."
        )
    # Both committed decks are placeholder builds, so the guard is the whole
    # repository and not just one filename: neither edition may take the
    # artwork inside it.
    if args.with_figures and (args.out.resolve() == REPO
                              or REPO in args.out.resolve().parents):
        parser.error(
            "the committed decks are the placeholder builds and must stay "
            "that way, because the figures are copyrighted. Give --out a "
            "path outside this repository for a deck with the artwork."
        )

    # Drawn before the deck, and every time, so a clone that has never built
    # anything still gets the real artwork on the first run.
    chartkit.generate(CHARTS, CHARTS_DIR, display_font=args.display_font)

    args.out.parent.mkdir(parents=True, exist_ok=True)
    slides, checks = deckkit.build(CHAPTER, args.out,
                                   display_font=args.display_font,
                                   figures_dir=figures_dir,
                                   charts_dir=CHARTS_DIR,
                                   edition=args.edition)
    # The answer sheet belongs to the instructor and is generated from the
    # chapter, not from the deck that was just rendered, so the student build
    # neither writes it nor can stale it.
    total_checks = sum(1 for _ in deckkit.iter_checks(CHAPTER))
    if args.edition == deckkit.TEACHING:
        write_checks(CHAPTER, CHECKS_OUT, total_checks)

    status = deckkit.figure_status(CHAPTER, figures_dir)
    placed = [n for n, _f, have in status if have]
    missing = [n for n, _f, have in status if not have]

    print(f"deck   : {_relative(args.out)}")
    print(f"edition : {args.edition}")
    if args.edition == deckkit.TEACHING:
        print(f"checks : {_relative(CHECKS_OUT)}")
    print(f"slides : {slides}")
    if checks:
        print(f"checkpoints : {checks} ({checks * 2} multiple choice items)")
    else:
        print(f"checkpoints : 0, and no speaker notes. "
              f"{total_checks} checks and {total_checks} reveals omitted.")
    print(f"figures : {len(placed)} placed, {len(missing)} as placeholders "
          f"(of {len(status)} figure slides)")
    if missing:
        print("        : " + ", ".join(missing))
    charts = deckkit.chart_status(CHAPTER, CHARTS_DIR)
    print(f"charts : {sum(1 for *_r, have in charts if have)} of "
          f"{len(charts)} drawn and placed "
          f"({', '.join(letter for letter, _f, _h in charts)})")
    print(f"figure source : {figures_dir or 'none, placeholder build'}")
    print(f"chart source : {_relative(CHARTS_DIR)}, generated by this build")
    print(f"display font : {args.display_font}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
